-- Fixed field catalogue (kit/fields.json): each spec row can belong to a
-- field (field_key) or a list (field_key + position); the rest is "Other".

alter table public.vehicle_specs rename column value to value_en;
alter table public.vehicle_specs rename column value_alt to value_ar;
alter table public.vehicle_specs alter column value_en drop not null;
alter table public.vehicle_specs
  add column field_key text,
  add column position int check (position >= 1),
  add constraint vehicle_specs_has_value check (coalesce(value_en, '') <> '' or coalesce(value_ar, '') <> '');

-- One value per field per vehicle (both documents print the same number).
create unique index vehicle_specs_field_once on public.vehicle_specs (vehicle_id, field_key)
  where field_key is not null and position is null;
create index vehicle_specs_list_idx on public.vehicle_specs (vehicle_id, field_key, position) where position is not null;

-- Label normalisation, mirroring normLabel() in web/src/lib/fields/index.ts.
create or replace function public.norm_label(t text) returns text language sql immutable as $$
  select trim(regexp_replace(regexp_replace(regexp_replace(
    translate(lower(normalize(coalesce(t, ''), NFKC)), 'أإآٱىة–—', 'اااايه--'),
    '[\u064B-\u0652\u0640]', '', 'g'),
    '\([^)]*\)', ' ', 'g'),
    '[[:space:][:punct:]،؛؟]+', ' ', 'g'))
$$;

